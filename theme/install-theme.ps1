# Installs the Fluent theme into PDF24 Toolbox (appends pdf24-fluent.css to themes.css).
#   .\install-theme.ps1              install or update (asks for admin rights)
#   .\install-theme.ps1 -Uninstall   restore the original look
# PDF24 updates overwrite themes.css: just run this again afterwards.
param([switch]$Uninstall)

$ErrorActionPreference = 'Stop'
$pdf24 = @("$env:ProgramFiles\PDF24", "${env:ProgramFiles(x86)}\PDF24") | Where-Object { Test-Path "$_\lib\toolbox\css\themes.css" } | Select-Object -First 1
if (-not $pdf24) { throw 'PDF24 Creator not found (expected lib\toolbox\css\themes.css under Program Files\PDF24).' }
$css    = "$pdf24\lib\toolbox\css\themes.css"
$theme  = Join-Path $PSScriptRoot 'pdf24-fluent.css'
$backup = "$css.pdf24-fluent-backup"
$begin  = '/* >>> pdf24-fluent (generated by install-theme.ps1, do not edit) >>> */'
$end    = '/* <<< pdf24-fluent <<< */'

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    $a = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$PSCommandPath`"")
    if ($Uninstall) { $a += '-Uninstall' }
    Start-Process powershell.exe -Verb RunAs -Wait -ArgumentList $a
    return
}

$text = [IO.File]::ReadAllText($css)
$i = $text.IndexOf($begin)
if ($i -ge 0) { $text = $text.Substring(0, $i).TrimEnd() + "`r`n" }
elseif (-not (Test-Path $backup)) { Copy-Item $css $backup }

if (-not $Uninstall) {
    $text += "`r`n$begin`r`n" + [IO.File]::ReadAllText($theme) + "`r`n$end`r`n"
}
[IO.File]::WriteAllText($css, $text, (New-Object System.Text.UTF8Encoding $false))

if ($Uninstall) { 'Original PDF24 look restored.' } else { 'Theme installed. Reopen PDF24 Toolbox (or press its reload button).' }
Start-Sleep 2
